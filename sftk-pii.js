// Israeli ת״ז check digit: weights alternate 1,2 across the 9 digits,
// anything over 9 has its digits summed, and the total must divide by 10.
function sftkPiiIlIdValid(value) {
  const s = String(value == null ? '' : value).trim();
  if (!/^\d{9}$/.test(s)) return false;
  let sum = 0;
  for (let i = 0; i < 9; i++) {
    let d = Number(s[i]) * ((i % 2) + 1);
    if (d > 9) d -= 9;
    sum += d;
  }
  return sum % 10 === 0;
}

// Luhn — credit cards and every scheme that copied them.
function sftkPiiLuhn(value) {
  const s = String(value == null ? '' : value).replace(/[\s-]/g, '');
  if (!/^\d{12,19}$/.test(s)) return false;
  let sum = 0, dbl = false;
  for (let i = s.length - 1; i >= 0; i--) {
    let d = Number(s[i]);
    if (dbl) { d *= 2; if (d > 9) d -= 9; }
    sum += d; dbl = !dbl;
  }
  return sum % 10 === 0;
}

// What do a field's ACTUAL values look like? Field names lie —
// Custom_Field_12__c can hold ת״ז numbers and no name heuristic would ever
// catch it — so this reads sampled values and returns the strongest match
// with its hit rate, or null when nothing clears the threshold. Pure: the
// caller samples, this only judges.
function sftkPiiDetectPattern(values) {
  const vals = (values || []).map(v => String(v == null ? '' : v).trim()).filter(Boolean);
  if (vals.length < 3) return null;   // too few to call a shape a pattern
  const tests = [
    ['il-id', v => sftkPiiIlIdValid(v)],
    ['credit-card', v => sftkPiiLuhn(v)],
    ['iban', v => sftkPiiIbanValid(v)],
    ['us-ssn', v => /^\d{3}-\d{2}-\d{4}$/.test(v)],
    ['il-mobile', v => /^(\+972[- ]?|0)5\d[- ]?\d{3}[- ]?\d{4}$/.test(v)],
    ['il-phone', v => /^(\+972[- ]?|0)[2-4689][- ]?\d{3}[- ]?\d{4}$/.test(v)],
    ['us-phone', v => /^\(?[2-9]\d{2}\)?[-. ]?\d{3}[-. ]?\d{4}$/.test(v)],
    ['uk-mobile', v => /^(\+44[- ]?|0)7\d{3}[- ]?\d{6}$/.test(v)],
    ['intl-phone', v => /^\+\d[\d\s().-]{6,18}\d$/.test(v)],
    ['email', v => /^[^\s@]+@[^\s@]+\.[A-Za-z]{2,}$/.test(v)],
  ];
  let best = null;
  for (const pair of tests) {
    let hits = 0;
    for (const v of vals) { try { if (pair[1](v)) hits++; } catch (_) { /* a bad value is a miss */ } }
    const rate = hits / vals.length;
    if (rate >= 0.8 && (!best || rate > best.rate)) {
      best = { pattern: pair[0], rate, hits, sampled: vals.length };
    }
  }
  if (best) return best;
  // v2 — free text that CONTAINS PII (an e-mail in a note, a phone in a
  // description): a fifth of the values holding a span is a pattern of its own
  // prose AROUND the span is what makes it free text — a bare identifier is
  // not (a mixed bag of bare values is no pattern at all)
  let withSpan = 0;
  for (const v of vals) { try { if (sftkPiiFindSpans(v).some(sp => sp.text.length < v.length)) withSpan++; } catch (_) { /* a bad value is a miss */ } }
  const rate = withSpan / vals.length;
  return rate >= 0.2 ? { pattern: 'text-pii', rate, hits: withSpan, sampled: vals.length } : null;
}

// Deterministic value in a pattern's shape, derived from the hash hex.
// Returns null when the field is too short to hold the shape — a truncated
// ת״ז is not a ת״ז, and the caller nulls (and COUNTS) instead of writing
// something that would fail validation anyway.
function sftkPiiPatternFormat(hex, patternId, fieldDesc, srcValue) {
  const n = BigInt('0x' + String(hex || '0'));
  const digits = (count, shift) =>
    String((n / (10n ** BigInt(shift))) % (10n ** BigInt(count))).padStart(count, '0');
  const choose = (arr, shift) => arr[Number((n / (10n ** BigInt(shift))) % BigInt(arr.length))];
  let out = null;
  if (patternId === 'il-id') {
    const base = digits(8, 0);
    let sum = 0;
    for (let i = 0; i < 8; i++) {
      let d = Number(base[i]) * ((i % 2) + 1);
      if (d > 9) d -= 9;
      sum += d;
    }
    out = base + String((10 - (sum % 10)) % 10);
  } else if (patternId === 'il-mobile') {
    out = choose(['050', '052', '053', '054', '055', '058'], 12) + '-' + digits(7, 0);
  } else if (patternId === 'il-phone') {
    out = choose(['02', '03', '04', '08', '09'], 12) + '-' + digits(7, 0);
  } else if (patternId === 'us-ssn') {
    out = String(900 + Number((n / 100000000000000n) % 100n)) + '-' + digits(2, 8) + '-' + digits(4, 0);
  } else if (patternId === 'credit-card') {
    const body = '4' + digits(14, 0);
    let sum = 0, dbl = true;   // the check digit sits to the right of body
    for (let i = body.length - 1; i >= 0; i--) {
      let d = Number(body[i]);
      if (dbl) { d *= 2; if (d > 9) d -= 9; }
      sum += d; dbl = !dbl;
    }
    out = body + String((10 - (sum % 10)) % 10);
  } else if (patternId === 'email') {
    out = n.toString(36).padStart(10, '0').slice(0, 10) + '@masked.invalid';
  } else if (patternId === 'person-name' || patternId === 'first-name'
             || patternId === 'last-name' || patternId === 'company') {
    const L = sftkPiiNameLists();
    const first = choose(L.first, 0), last = choose(L.last, 8);
    out = patternId === 'first-name' ? first
      : patternId === 'last-name' ? last
      : patternId === 'company' ? `${choose(L.company, 0)} ${choose(L.suffix, 8)}`
      : `${first} ${last}`;
  } else if (patternId === 'digits') {
    const srcDigits = String(srcValue == null ? '' : srcValue).replace(/\D/g, '').length;
    out = digits(Math.max(1, Math.min(18, srcDigits || 6)), 0);
  }
  if (out == null) return null;
  const max = (fieldDesc && typeof fieldDesc.length === 'number' && fieldDesc.length > 0) ? fieldDesc.length : null;
  if (max !== null && out.length > max) return null;   // never truncate a shape
  return out;
}

